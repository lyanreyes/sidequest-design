// Builds preview.html and plugin/code.js from the shared sources in src/.
const fs = require("fs");
const path = require("path");
const src = (f) => fs.readFileSync(path.join(__dirname, "src", f), "utf8");

const shared = ["tokens.js", "screens.js", "designsystem.js"].map(src).join("\n");

const cssVars = (() => {
  // evaluate tokens.js to read the color list
  const TOKENS = new Function(src("tokens.js") + "\nreturn TOKENS;")();
  return TOKENS.colors.map((c) => `--${c[0]}: ${c[1]};`).join(" ");
})();

const preview = src("preview-template.html")
  .replace("/*TOKENS*/", cssVars)
  .replace("/*SCRIPTS*/", shared + "\n" + src("render-html.js"));
fs.writeFileSync(path.join(__dirname, "preview.html"), preview);

const plugin = "// AUTO-GENERATED by build.js. Edit files in src/ instead.\n" + shared + "\n" + src("render-figma.js");
fs.writeFileSync(path.join(__dirname, "plugin", "code.js"), plugin);
console.log("Built preview.html and plugin/code.js");
